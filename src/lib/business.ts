import { BusinessProfile, Prisma } from "@prisma/client";

// Fetch the same allowlist that is exposed publicly. Private verification files,
// payment details and reviewer notes never enter directory query results.
export const publicBusinessSelect = {
  id: true,
  refNumber: true,
  status: true,
  businessName: true,
  businessNameEn: true,
  ownerName: true,
  ownerNameEn: true,
  brandName: true,
  categoryId: true,
  category: {
    select: { id: true, slug: true, nameMr: true, nameEn: true, icon: true },
  },
  subCategory: true,
  subCategoryEn: true,
  productsServices: true,
  productsServicesEn: true,
  description: true,
  descriptionEn: true,
  establishedYear: true,
  businessClassification: true,
  ownershipType: true,
  workNature: true,
  premisesOwnership: true,
  employeeCountTotal: true,
  officeCity: true,
  officeCityEn: true,
  officeTaluka: true,
  officeTalukaEn: true,
  officeDistrict: true,
  officeDistrictEn: true,
  isAddressPublic: true,
  officeAddress: true,
  officeAddressEn: true,
  officePincode: true,
  factoryAddress: true,
  factoryCity: true,
  factoryTaluka: true,
  factoryDistrict: true,
  factoryPincode: true,
  phone: true,
  email: true,
  website: true,
  logoUrl: true,
  publishedAt: true,
} satisfies Prisma.BusinessProfileSelect;

type PublicBusinessRecord = Prisma.BusinessProfileGetPayload<{
  select: typeof publicBusinessSelect;
}>;

// Only explicitly public fields may leave the directory API.
export function publicBusiness(
  b: PublicBusinessRecord | (BusinessProfile & { category?: unknown }),
) {
  return {
    id: b.id,
    refNumber: b.refNumber,
    status: b.status,
    businessName: b.businessName,
    businessNameEn: b.businessNameEn,
    ownerName: b.ownerName,
    ownerNameEn: b.ownerNameEn,
    brandName: b.brandName,
    categoryId: b.categoryId,
    category: b.category,
    subCategory: b.subCategory,
    subCategoryEn: b.subCategoryEn,
    productsServices: b.productsServices,
    productsServicesEn: b.productsServicesEn,
    description: b.description,
    descriptionEn: b.descriptionEn,
    establishedYear: b.establishedYear,
    businessClassification: b.businessClassification,
    ownershipType: b.ownershipType,
    workNature: b.workNature,
    premisesOwnership: b.premisesOwnership,
    employeeCountTotal: b.employeeCountTotal,
    officeCity: b.officeCity,
    officeCityEn: b.officeCityEn,
    officeTaluka: b.officeTaluka,
    officeTalukaEn: b.officeTalukaEn,
    officeDistrict: b.officeDistrict,
    officeDistrictEn: b.officeDistrictEn,
    isAddressPublic: b.isAddressPublic,
    ...(b.isAddressPublic
      ? {
          officeAddress: b.officeAddress,
          officeAddressEn: b.officeAddressEn,
          officePincode: b.officePincode,
          factoryAddress: b.factoryAddress,
          factoryCity: b.factoryCity,
          factoryTaluka: b.factoryTaluka,
          factoryDistrict: b.factoryDistrict,
          factoryPincode: b.factoryPincode,
        }
      : {}),
    phone: b.phone,
    email: b.email,
    website: /^https?:\/\//i.test(b.website || "") ? b.website : null,
    logoUrl: b.logoUrl?.startsWith("/api/files/") ? b.logoUrl : null,
    publishedAt: b.publishedAt?.toISOString() || null,
  };
}
